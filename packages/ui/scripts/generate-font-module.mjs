/**
 * Regenerates `src/fonts/plex-latin.ts` from the `.woff2` files beside it.
 *
 * The binaries are the artifact the OFL covers and the thing a reader can verify; the generated
 * module is how five bundlers get it with no asset plumbing (see `src/fonts/index.ts` for why it
 * is base64 rather than `url()`). `src/fonts/fonts.test.ts` re-encodes the binaries and fails if
 * the two ever disagree, so this script is the declared way to make them agree again.
 *
 *   node packages/ui/scripts/generate-font-module.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FONTS = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "fonts");
const WEIGHTS = [400, 500, 600];

const constant = (weight) => `PLEX_LATIN_${weight}`;

const body = WEIGHTS.map((weight) => {
  const file = join(FONTS, `ibm-plex-sans-latin-${weight}-normal.woff2`);
  return `export const ${constant(weight)} =\n  "${readFileSync(file).toString("base64")}";\n`;
}).join("\n");

writeFileSync(
  join(FONTS, "plex-latin.ts"),
  `// GENERATED by scripts/generate-font-module.mjs — do not edit by hand.\n` +
    `// Source: src/fonts/ibm-plex-sans-latin-{400,500,600}-normal.woff2 (OFL 1.1, see OFL.txt).\n` +
    `// Guarded by src/fonts/fonts.test.ts, which re-encodes those files and compares.\n\n` +
    body,
);

process.stdout.write(`wrote plex-latin.ts (${WEIGHTS.length} weights)\n`);
