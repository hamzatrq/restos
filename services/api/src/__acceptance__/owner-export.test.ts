type ExportState = "queued" | "running" | "ready" | "failed";
const EXPORT_STATES: readonly ExportState[] = ["queued", "running", "ready", "failed"];

type ExportRequestRecord = {
  export_id: string;
  org_id: string;
  requested_by_user_id: string;
  requested_at: number;
  state: ExportState;
  bundle: string | null;
};

type ExportRequests = {
  request(input: {
    org_id: string;
    requested_by_user_id: string;
    requested_at: number;
  }): Promise<ExportRequestRecord>;
  get(org_id: string, export_id: string): Promise<ExportRequestRecord | null>;
  list(org_id: string): Promise<readonly ExportRequestRecord[]>;
};

