/**
 * The store. **Deliberately undefended** — it answers exactly the org it is asked about, the way
 * `where org_id = $1` does, and it never validates that the org it was handed is the org the
 * caller is entitled to. That check is the SERVICE's, and a store that performed it would mask
 * the absence of the service's own (`tenant-isolation.test.ts`'s rule 1).
 */
const memoryExportRequests = (): ExportRequests & {
  seed(record: ExportRequestRecord): void;
  all(): readonly ExportRequestRecord[];
} => {
  const rows: ExportRequestRecord[] = [];
  let minted = 0;
  return {
    seed: (record) => {
      rows.push(record);
    },
    all: () => rows,
    request: async (input) => {
      minted += 1;
      const record: ExportRequestRecord = {
        export_id: `export-${String(minted)}`,
        org_id: input.org_id,
        requested_by_user_id: input.requested_by_user_id,
        requested_at: input.requested_at,
        state: "queued",
        bundle: null,
      };
      rows.push(record);
      return record;
    },
    get: async (org_id, export_id) =>
      rows.find((row) => row.org_id === org_id && row.export_id === export_id) ?? null,
    list: async (org_id) => rows.filter((row) => row.org_id === org_id),
  };
};

type Rpc = { status: number; body: Record<string, unknown> };
const QUERIES = new Set(["governance.exportStatus", "governance.exports"]);

type Host = {
  call(path: string, input: unknown, bearer?: string): Promise<Rpc>;
  login(email: string): Promise<string>;
  exports: ReturnType<typeof memoryExportRequests>;
};

const dataOf = (rpc: Rpc): unknown => {
  const result = (rpc.body as { result?: { data?: unknown } }).result;
  if (result === undefined) throw new Error(`expected a result, got ${JSON.stringify(rpc.body)}`);
  return superjson.deserialize(result.data as never);
};

const errorOf = (rpc: Rpc): { code?: string; message?: string } =>
  ((rpc.body as { error?: { json?: { message?: string; data?: { code?: string } } } }).error
    ?.json ?? {}) as { code?: string; message?: string };

const codeOf = (rpc: Rpc): string =>
  (
    rpc.body as { error?: { json?: { data?: { code?: string } } } }
  ).error?.json?.data?.code?.toString() ?? "";

